// Exercise the production speaker gate and the launcher's actual data-channel handler.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const read = (p) => readFileSync(new URL(p, import.meta.url), 'utf8');
const ctx = vm.createContext({ Date, console });
vm.runInContext(read('../../web/voice-audio.js') + '\nglobalThis.VoiceAudio = VoiceAudio;', ctx);
const track = { enabled: true }, speaker = { muted: false }, gate = new ctx.VoiceAudio(track, speaker);
const turn = (type, role) => ({ type: 'turn.' + type, turn: { role } });
assert.equal(track.enabled, true);
gate.event(turn('created', 'assistant'));
assert.equal(track.enabled, false, 'speaker echo cannot reach the server');
gate.sample(0, Date.now() + 5000);
assert.equal(track.enabled, false, 'an intra-reply pause must not reopen the mic');
gate.event(turn('done', 'assistant'));
gate.sample(.1, Date.now() + 1000);
gate.sample(0, Date.now() + 1300);
assert.equal(track.enabled, false, 'buffered playback and its echo tail stay gated');
gate.sample(0, Date.now() + 1600);
assert.equal(track.enabled, true, 'listening resumes after playback drains');
gate.toggle(); gate.event(turn('created', 'assistant')); gate.event(turn('done', 'assistant')); gate.sample(0, Date.now() + 1000);
assert.equal(track.enabled, false, 'manual mute persists after the reply');
gate.toggle(); gate.event(turn('created', 'assistant')); gate.toggle();
assert.equal(track.enabled, true, 'tap to interrupt opens the mic');
assert.equal(speaker.muted, true, 'tap to interrupt silences playback first');
gate.event({ type: 'output_transcript.added' });
assert.equal(track.enabled, true, 'old output cannot close the interruption mic');
gate.event(turn('created', 'user')); gate.event(turn('created', 'assistant'));
assert.equal(track.enabled, false); assert.equal(speaker.muted, false);
gate.active = false; gate.apply(); gate.event(turn('created', 'assistant'));
assert.equal(speaker.muted, true, 'a closed warm session cannot unmute itself');
gate.track = { enabled: true }; gate.active = true; gate.apply();
assert.equal(gate.track.enabled, false, 'warm reopen preserves the current reply gate');
const nodes = new Map(['#voice', '#va', '#vu', '.tx'].map(k => [k, { textContent: '', classList: { add() {} }, scrollHeight: 900, scrollTop: 0 }]));
Object.assign(ctx, { $: (k) => nodes.get(k), send() {}, micTrack: track, voiceAudio: gate, voiceLive: false, on: (name, fn) => { ctx[name] = fn; }, V: { state() {} } });
const app = read('../../web/app.js');
vm.runInContext(app.slice(app.indexOf('function voiceMessage('), app.indexOf('function voiceDrop(')), ctx);
for (const name of ['voice.transcript', 'voice.result']) vm.runInContext(app.split('\n').find(l => l.startsWith(`on('${name}',`)), ctx);
ctx.voiceMessage(turn('created', 'user'));
const parts = [' one', ' two', ' three', ' forty', ' fifty', ' sixty'];
for (const [i, text] of parts.entries()) ctx.voiceMessage({ type: 'output_transcript.added', item: { id: 'item_' + i, text } });
ctx['voice.transcript']({ role: 'assistant', text: 'one two three', final: true });
ctx['voice.result']({ text: 'old backend result' });
assert.equal(nodes.get('#va').textContent, parts.join(''), 'all item ids stream and stale sideband cannot overwrite');
assert.equal(nodes.get('.tx').scrollTop, 900, 'newest text scrolls into view');
ctx.voiceMessage(turn('created', 'user'));
assert.equal(nodes.get('#va').textContent, '', 'the next user turn starts a fresh reply');
console.log('PASS: reply gating, drain, mute, interruption, warm reuse, streaming transcript, stale events, scrolling');
